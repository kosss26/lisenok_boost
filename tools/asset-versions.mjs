// Hash actual encoded bytes per URL: changing one clip never invalidates its neighbours.
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const versions = {};
for (const root of ["public", "tmp/media-cache"]) {
  for (const folder of ["art", "sfx", "voice", "music"]) {
    const dir = join(root, folder);
    if (!existsSync(dir)) continue;
    for (const name of readdirSync(dir).sort()) {
      versions[`/${folder}/${name}`] = createHash("sha256")
        .update(readFileSync(join(dir, name)))
        .digest("hex")
        .slice(0, 12);
    }
  }
}
const body = `// Generated by tools/asset-versions.mjs — do not edit by hand.\nexport const ASSET_VERSIONS: Record<string, string> = ${JSON.stringify(versions, null, 2)};\n`;
const target = "src/game/asset-versions.ts";
if (!existsSync(target) || readFileSync(target, "utf8") !== body) writeFileSync(target, body);
console.log(`asset versions: ${Object.keys(versions).length} individual files`);
