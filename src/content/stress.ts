const CYR = "А-Яа-яЁё";
const WORD = new RegExp(`(?<![${CYR}+])[${CYR}]+(?![${CYR}+])`, "g");

/** "Как здорово!" -> "Как зд+орово!" (keeps the capital letter). */
export function stressed(text: string): string {
  return text.replace(WORD, (w) => {
    const mark = STRESS[w.toLowerCase()];
    if (!mark) return w;
    const at = mark.indexOf("+");
    return w.slice(0, at) + "+" + w.slice(at);
  });
}
